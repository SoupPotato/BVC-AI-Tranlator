# Bundles admin.html + css + js into one self-contained file:
#   dist/BVC-Translation-Control.html
# Double-click that file (opens in Chrome/Edge) to run the control tool from the desktop.
# Re-run this script after changing js/config.js or any code:
#   powershell -ExecutionPolicy Bypass -File tools\build-standalone.ps1

$ErrorActionPreference = "Stop"
$root = Split-Path -Parent $PSScriptRoot
$utf8 = New-Object System.Text.UTF8Encoding($false)
function ReadText($rel) { [IO.File]::ReadAllText((Join-Path $root $rel), $utf8) }

# Order matters: each module only uses names defined above it.
$modules = "js/config.js", "js/languages.js", "js/translate.js", "js/audio.js", "js/speech.js", "js/transport.js", "js/admin.js"

$js = foreach ($m in $modules) {
  $src = ReadText $m
  $src = [regex]::Replace($src, '(?m)^import\s.*?from\s+"\./[^"]+";\s*$', '')   # local imports
  $src = [regex]::Replace($src, '(?m)^export\s+', '')                           # export keywords
  "// ===== $m =====`n$src"
}
$js = $js -join "`n"
if ($js -match '</script') { throw "Bundled JS contains '</script' and would break the HTML." }

$html = ReadText "admin.html"
$css = ReadText "css/style.css"
$cssTag = '<link rel="stylesheet" href="css/style.css" />'
$jsTag = '<script type="module" src="js/admin.js"></script>'
if (-not $html.Contains($cssTag) -or -not $html.Contains($jsTag)) { throw "admin.html tags changed; update this script." }
$html = $html.Replace($cssTag, "<style>`n$css`n</style>")
$html = $html.Replace($jsTag, "<script type=`"module`">`n$js`n</script>")
$stamp = Get-Date -Format "yyyy-MM-dd HH:mm"
$html = $html.Replace("<head>", "<head>`n  <!-- Standalone build $stamp - generated by tools/build-standalone.ps1; edit the source files, not this one. -->")

$out = Join-Path $root "dist"
New-Item -ItemType Directory -Force $out | Out-Null
$file = Join-Path $out "BVC-Translation-Control.html"
[IO.File]::WriteAllText($file, $html, $utf8)
Write-Output "Built $file ($([math]::Round((Get-Item $file).Length / 1KB)) KB)"
